"""Reference Verilog-2001 generator for an exported LUT-native classifier (Section 8.5).

Datapath, one feature vector per `valid_in` (one per second in the real system):
  stage 0  register the feature vector and artefact flags
  stage 1  comparators (one per threshold kept) -> input bits; LUT layer 1
           (localparam [2^n-1:0] T_<l>_<i> = ...; assign y = T[{x_f..x_a}]) ; registered
  stage 2+ further LUT layers, one register stage each
  next     popcount of each class group (adder tree), score = pop1 - pop0; registered
  last     decision = score >= THRESH and gate clear; k-of-10 shift register and counter
Outputs: score, decision, alarm, out_valid (fixed latency). Plain synthesizable Verilog-2001;
no vendor primitives, no multipliers.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np


def _w(n: int) -> int:
    return max(1, math.ceil(math.log2(n + 1)))


def generate(pkg: dict, out_path: Path, module: str = "lutnet_classifier", debug: bool = False) -> dict:
    """debug=True adds two outputs for the live demo: dbg_bits (the comparator bits, registered together with the
    first LUT layer) and dbg_luts (the last LUT layer's outputs); score/decision/alarm are unchanged."""
    feats = pkg["thresholds"]["features"]
    bits = pkg["thresholds"]["input_bits"]
    layers = pkg["mapping"]["layers"]
    tables = pkg["luts"]["layers"]
    hd = pkg["head"]
    widths = [f["width_bits"] for f in feats]
    offs = np.concatenate(([0], np.cumsum(widths))).astype(int)
    fidx = {f["name"]: i for i, f in enumerate(feats)}
    total_w = int(offs[-1])
    n_last = layers[-1]["n_luts"]
    a0, a1 = hd["groups"]["background"]
    b0, b1 = hd["groups"]["seizure"]
    pw = _w(max(a1 - a0, b1 - b0))
    sw = pw + 1
    L = []
    w = L.append
    w("// Generated by src/hw/verilog.py -- do not edit. Reference model of the LUT-native classifier.")
    w(f"// {len(bits)} comparators, {sum(l['n_luts'] for l in layers)} LUT{layers[0]['n_inputs']} neurons in "
      f"{len(layers)} layer(s), score = popcount[{b0}:{b1}) - popcount[{a0}:{a1}), k={hd['k']} of {hd['n']}.")
    w("`timescale 1ns/1ps")
    w(f"module {module} (")
    w("    input  wire clk,")
    w("    input  wire rst,")
    w("    input  wire valid_in,")
    w(f"    input  wire [{total_w - 1}:0] features,   // packed signed features, feature 0 in the LSBs")
    w("    input  wire [1:0] artefact,")
    w(f"    output reg  signed [{sw - 1}:0] score,")
    w("    output reg  decision,")
    w("    output reg  alarm,")
    if debug:
        w("    output reg  out_valid,")
        w(f"    output wire [{len(bits) - 1}:0] dbg_bits,")
        w(f"    output wire [{layers[-1]['n_luts'] - 1}:0] dbg_luts")
    else:
        w("    output reg  out_valid")
    w(");")
    w(f"    reg [{total_w - 1}:0] f_r;")
    w("    reg [1:0] art_r;")
    w("    reg v0;")
    w("    always @(posedge clk) begin")
    w("        if (rst) begin v0 <= 1'b0; f_r <= 0; art_r <= 2'b00; end")
    w("        else begin v0 <= valid_in; f_r <= features; art_r <= artefact; end")
    w("    end")
    for i, f in enumerate(feats):
        w(f"    wire signed [{widths[i] - 1}:0] x{i} = f_r[{offs[i + 1] - 1}:{offs[i]}];   // {f['name']}")
    w(f"    wire [{len(bits) - 1}:0] b;")
    for i, bdef in enumerate(bits):
        j = fidx[bdef["feature"]]
        t = int(bdef["threshold"])
        wd = widths[j]
        lo, hi = -(1 << (wd - 1)), (1 << (wd - 1)) - 1
        if t >= hi:            # a W-bit signed feature can never exceed it: constant 0 (no comparator)
            w(f"    assign b[{i}] = 1'b0;   // threshold {t} >= max {hi} of {feats[j]['name']}")
        elif t < lo:           # always exceeded: constant 1
            w(f"    assign b[{i}] = 1'b1;   // threshold {t} < min {lo} of {feats[j]['name']}")
        else:
            lit = f"-{wd}'sd{abs(t)}" if t < 0 else f"{wd}'sd{t}"
            w(f"    assign b[{i}] = (x{j} > {lit});")
    prev, prev_w = "b", len(bits)
    art_pipe = ["art_r"]
    for li, (layer, tabs) in enumerate(zip(layers, tables)):
        n_in = layer["n_inputs"]
        n = layer["n_luts"]
        w(f"    // layer {li + 1}: {n} LUT{n_in}")
        w(f"    wire [{n - 1}:0] y{li};")
        for i, (inp, tt) in enumerate(zip(layer["inputs"], tabs)):
            w(f"    localparam [{(1 << n_in) - 1}:0] T{li}_{i} = {1 << n_in}'h{tt};")
            addr = ", ".join(f"{prev}[{int(k)}]" for k in reversed(inp))
            w(f"    assign y{li}[{i}] = T{li}_{i}[{{{addr}}}];")
        w(f"    reg [{n - 1}:0] h{li};")
        w(f"    reg [1:0] art{li};")
        w(f"    reg v{li + 1};")
        w("    always @(posedge clk) begin")
        w(f"        if (rst) begin v{li + 1} <= 1'b0; h{li} <= 0; art{li} <= 2'b00; end")
        w(f"        else begin v{li + 1} <= v{li}; h{li} <= y{li}; art{li} <= {art_pipe[-1]}; end")
        w("    end")
        prev, prev_w = f"h{li}", n
        art_pipe.append(f"art{li}")
        if debug and li == 0:
            w(f"    reg [{len(bits) - 1}:0] b_r;   // debug: comparator bits of the window now in h0")
            w("    always @(posedge clk) begin if (rst) b_r <= 0; else b_r <= b; end")
            w("    assign dbg_bits = b_r;")
    nl = len(layers)
    if debug:
        w(f"    assign dbg_luts = {prev};")
    w("    // popcount per class (behavioural adder tree, synthesises to LUTs + carry chains)")
    w(f"    function [{pw - 1}:0] popcount_bg; input [{a1 - a0 - 1}:0] v; integer i; begin")
    w(f"        popcount_bg = 0; for (i = 0; i < {a1 - a0}; i = i + 1) popcount_bg = popcount_bg + v[i]; end endfunction")
    w(f"    function [{pw - 1}:0] popcount_sz; input [{b1 - b0 - 1}:0] v; integer i; begin")
    w(f"        popcount_sz = 0; for (i = 0; i < {b1 - b0}; i = i + 1) popcount_sz = popcount_sz + v[i]; end endfunction")
    w(f"    wire signed [{sw - 1}:0] score_c = $signed({{1'b0, popcount_sz({prev}[{b1 - 1}:{b0}])}}) - "
      f"$signed({{1'b0, popcount_bg({prev}[{a1 - 1}:{a0}])}});")
    gate = {"none": "1'b0", "both": f"({art_pipe[-1]}[0] & {art_pipe[-1]}[1])",
            "any": f"({art_pipe[-1]}[0] | {art_pipe[-1]}[1])"}[hd["artefact_gate"]]
    thr = int(hd["decision_threshold"])
    thr_lit = f"-{sw}'sd{abs(thr)}" if thr < 0 else f"{sw}'sd{thr}"
    w(f"    wire dec_c = (score_c >= {thr_lit}) & ~{gate};")
    w(f"    reg [{hd['n'] - 1}:0] hist;")
    cw = _w(hd["n"])
    w(f"    function [{cw - 1}:0] ones; input [{hd['n'] - 1}:0] v; integer i; begin")
    w(f"        ones = 0; for (i = 0; i < {hd['n']}; i = i + 1) ones = ones + v[i]; end endfunction")
    w(f"    wire [{hd['n'] - 1}:0] hist_next = {{hist[{hd['n'] - 2}:0], dec_c}};")
    w("    always @(posedge clk) begin")
    w("        if (rst) begin score <= 0; decision <= 1'b0; alarm <= 1'b0; out_valid <= 1'b0; hist <= 0; end")
    w(f"        else begin out_valid <= v{nl};")
    w(f"            if (v{nl}) begin score <= score_c; decision <= dec_c; hist <= hist_next;")
    w(f"                alarm <= (ones(hist_next) >= {cw}'d{hd['k']}); end")
    w("        end")
    w("    end")
    w("endmodule")
    Path(out_path).write_text("\n".join(L) + "\n")
    return {"latency_cycles": nl + 2, "feature_bus_bits": total_w, "score_bits": sw, "widths": widths}


def make_testbench(pkg: dict, info: dict, vec_path: Path, n_vectors: int, out_path: Path,
              module: str = "lutnet_classifier") -> None:
    """Testbench reading hex vectors: one line per second = {expected alarm, decision, score, artefact, features}."""
    sw, tw = info["score_bits"], info["feature_bus_bits"]
    line_w = 1 + 1 + sw + 2 + tw
    L = ["`timescale 1ns/1ps", f"module tb_{module};",
         "    reg clk = 0, rst = 1, valid_in = 0;",
         f"    reg [{tw - 1}:0] features = 0;", "    reg [1:0] artefact = 0;",
         f"    wire signed [{sw - 1}:0] score;", "    wire decision, alarm, out_valid;",
         f"    reg [{line_w - 1}:0] mem [0:{n_vectors - 1}];",
         "    integer i, n_out, errors;",
         f"    {module} dut(.clk(clk), .rst(rst), .valid_in(valid_in), .features(features), .artefact(artefact),",
         "                 .score(score), .decision(decision), .alarm(alarm), .out_valid(out_valid));",
         "    always #5 clk = ~clk;",
         f"    reg [{line_w - 1}:0] exp_line;",
         "    always @(posedge clk) if (!rst && out_valid) begin",
         "        exp_line = mem[n_out];",
         f"        if (score !== exp_line[{sw + 2 + tw - 1}:{2 + tw}] || decision !== exp_line[{line_w - 2}] || "
         f"alarm !== exp_line[{line_w - 1}]) begin",
         "            errors = errors + 1;",
         "            if (errors < 10) $display(\"MISMATCH at %0d: score %0d exp %0d, dec %b exp %b, alarm %b exp %b\", n_out, score,",
         f"                $signed(exp_line[{sw + 2 + tw - 1}:{2 + tw}]), decision, exp_line[{line_w - 2}], alarm, exp_line[{line_w - 1}]);",
         "        end",
         "        n_out = n_out + 1;",
         "    end",
         "    initial begin",
         f"        $readmemh(\"{Path(vec_path).name}\", mem);",
         "        n_out = 0; errors = 0;",
         "        repeat (3) @(posedge clk); rst = 0;",
         f"        for (i = 0; i < {n_vectors}; i = i + 1) begin",
         "            @(negedge clk);",
         f"            features = mem[i][{tw - 1}:0]; artefact = mem[i][{tw + 1}:{tw}]; valid_in = 1;",
         "        end",
         "        @(negedge clk); valid_in = 0;",
         f"        repeat ({info['latency_cycles'] + 3}) @(posedge clk);",
         f"        if (errors == 0 && n_out == {n_vectors}) $display(\"PASS %0d vectors, 0 mismatches\", n_out);",
         "        else $display(\"FAIL %0d mismatches, %0d outputs\", errors, n_out);",
         "        $finish;",
         "    end",
         "endmodule"]
    Path(out_path).write_text("\n".join(L) + "\n")


def write_vectors(pkg: dict, info: dict, X: np.ndarray, artefact: np.ndarray, golden: dict, path: Path,
                  full_features: bool = False) -> int:
    """Hex test vectors matching testbench(): {alarm, decision, score, artefact, packed features}.
    X: the model's input columns, or with full_features=True all 117 features in spec order."""
    widths = info["widths"]
    sw = info["score_bits"]
    cols = [f["spec_index" if full_features else "column"] for f in pkg["thresholds"]["features"]]
    lines = []
    for t in range(len(X)):
        v = 0
        pos = 0
        for c, wd in zip(cols, widths):
            v |= (int(X[t, c]) & ((1 << wd) - 1)) << pos
            pos += wd
        v |= (int(artefact[t, 0]) | (int(artefact[t, 1]) << 1)) << pos
        pos += 2
        v |= (int(golden["score"][t]) & ((1 << sw) - 1)) << pos
        pos += sw
        v |= int(golden["decision"][t]) << pos
        pos += 1
        v |= int(golden["alarm"][t]) << pos
        pos += 1
        lines.append(f"{v:0{(pos + 3) // 4}x}")
    Path(path).write_text("\n".join(lines) + "\n")
    return len(lines)


def simulate(work_dir: Path, rtl: Path, tb: Path, simulator: str = "iverilog") -> tuple[bool, str]:
    import subprocess
    exe = Path(work_dir) / "sim.vvp"
    r = subprocess.run(["iverilog", "-g2001", "-o", str(exe), str(rtl), str(tb)], capture_output=True, text=True)
    if r.returncode:
        return False, r.stderr
    r = subprocess.run(["vvp", "-n", str(exe)], capture_output=True, text=True, cwd=work_dir)
    return ("PASS" in r.stdout and "FAIL" not in r.stdout), r.stdout + r.stderr
