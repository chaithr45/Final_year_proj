#!/usr/bin/env python3
"""Detector-derived front-end specification and per-channel power (MS_SPEC.md 1.2 step 7, 1.3).

From the tolerance limits to an analog front-end spec per modality, then to power. Default source: the full-data
limits ms/results/phase1/spec_limits.json (ms/py/full_spec.py) when it exists, else the subset limits in
tolerance.json (labelled "subset only"):

  * ADC resolution: the LSB limit q and the clip limit C give N = ceil(log2(2 C / q)) bits, i.e. an ideal
    quantisation-limited SNDR of 6.02 N + 1.76 dB for a full-scale sine. ADC power at that SNDR and
    fsnyq = 256 Hz from the Murmann survey (ms/py/adc_power.py: FOM scaling over designs of similar SNDR, and
    the lowest power any low-rate design reached).
  * Amplifier: input-referred noise limit v_n (uV rms over 0.5-100 Hz) -> noise-set supply current from the NEF
    definition, I = NEF^2 * pi * U_T * 4kT * BW / (2 v_n^2), P = I * VDD. NEF is a PARAMETER (2, 3, 5: an
    illustrative range, not values read from papers); T = 300 K; BW = 99.5 Hz; VDD = 1.8 V (the SKY130 core devices,
    nfet_01v8/pfet_01v8). This is the power the noise alone demands; a real amplifier also spends power on CMRR,
    input range, settling and chopping, so it is a lower bound.
  A limit that is "beyond grid" gives a bound (the spec is at least that loose); "none tolerated" gives a spec
  tighter than the mildest level tested.
  * Combined point (step 7b, LOG L21): the levels at which every impairment holds AT ONCE, from the back-off
    (combined_backoff_full.json if it passed, else combined_backoff.json, labelled "subset only"). Where it exists,
    the ADC bits and the power are computed from it (the binding spec), and the one-at-a-time values are kept beside it.

Usage: python ms/py/spec_table.py [tolerance.json] -> ms/results/phase1/spec.json, spec_table.md
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "ms/py"))
P1 = REPO / "ms/results/phase1"
K_B, Q_E, T_K = 1.380649e-23, 1.602176634e-19, 300.0
U_T = K_B * T_K / Q_E
BW_HZ, VDD, FSNYQ = 99.5, 1.8, 256.0
NEFS = (2.0, 3.0, 5.0)
CHANNELS = {"eeg": 2, "ecg": 1, "emg": 1}


def amp_current(nef: float, vn_rms: float, bw: float = BW_HZ) -> float:
    """Supply current (A) an amplifier of noise efficiency factor nef needs for input noise vn_rms (V rms)."""
    return nef ** 2 * math.pi * U_T * 4 * K_B * T_K * bw / (2 * vn_rms ** 2)


def bits_for(clip_uv: float, lsb_uv: float) -> int:
    return math.ceil(math.log2(2 * clip_uv / lsb_uv))


def limit(fams: dict, key: str):
    f = fams.get(key)
    if f is None:
        return None, "not swept"
    lv = f["levels"]
    if f["status"] == "none tolerated":
        return lv[0]["level"], "tighter than"
    if f["status"] == "pending":
        return None, "pending"
    return f["limit"], ("at least" if f["status"] == "beyond grid" else "limit")


def combined_levels(tol: dict, p1: Path = P1) -> tuple[dict, str | None]:
    """family key -> ("value", level) or ("off", None) at the final step of the back-off that passed."""
    for name, basis in (("combined_backoff_full.json", "combined point, full data"),
                        ("combined_backoff.json", "combined point, subset only")):
        p = p1 / name
        if not p.exists():
            continue
        b = json.loads(p.read_text())
        if b.get("status") != "passed" or b.get("preview"):
            continue
        fams = {k: f for g in tol["grids"].values() for k, f in g["families"].items()}
        out = {}
        for k, lname in b["steps"][-1]["levels"].items():
            if lname == "off":
                out[k] = ("off", None)
            else:
                out[k] = ("value", next(x["level"] for x in fams[k]["levels"] if x["name"] == lname))
        return out, basis + f" (step {b['steps'][-1]['step']})"
    return {}, None


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else (P1 / "spec_limits.json" if (P1 / "spec_limits.json").exists()
                                                         else P1 / "tolerance.json")
    basis = "full data (D-MS10 + Wilcoxon)" if src.name == "spec_limits.json" else "subset only (not yet confirmed)"
    tol = json.loads(src.read_text())
    import adc_power
    survey = adc_power.load()
    comb, comb_basis = combined_levels(tol)
    spec, md = {}, ["# Detector-derived front-end specification (Phase 1)\n",
                    f"Generated by `python ms/py/spec_table.py` from `{src.relative_to(REPO) if src.is_relative_to(REPO) else src}`. "
                    "Input-referred values. 'at least' = every tested level passed (bound); 'tighter than' = even the "
                    "mildest level failed.\n"]
    for mod, n_ch in CHANNELS.items():
        if mod not in tol["grids"]:
            continue
        fams = tol["grids"][mod]["families"]
        g = lambda k: limit(fams, f"{mod}/{k}")
        s = {k: dict(zip(("value", "kind"), g(k))) for k in
             ("white", "lsb", "clip", "pink", "gain+", "gain-", "offset", "drift", "mains50", "mains250", "hp", "lp")}
        row = {"limits": s, "channels": n_ch}
        cm = {k: comb.get(f"{mod}/{k}") for k in s} if comb else {}
        if cm:
            row["combined"] = {k: (None if v is None else (v[1] if v[0] == "value" else "off")) for k, v in cm.items()}
        use = lambda k: (cm[k][1] if cm.get(k) and cm[k][0] == "value" else None) if cm else s[k]["value"]
        row["power_basis"] = comb_basis if cm else basis
        if use("white"):
            vn = use("white") * 1e-6
            row["noise_density_nV_rtHz"] = use("white") * 1e3 / math.sqrt(BW_HZ)
            row["amp_power_uW_per_channel"] = {f"NEF {n:g}": amp_current(n, vn) * VDD * 1e6 for n in NEFS}
        if use("lsb") and (use("clip") or not cm):
            n_bits = bits_for(use("clip") or 8192.0, use("lsb"))
            sndr = 6.02 * n_bits + 1.76
            a = adc_power.at_sndr(survey, sndr, FSNYQ)
            row["adc"] = {"bits": n_bits, "sndr_dB": sndr,
                          "P_walden_best_uW": a.get("walden", {}).get("P_best_W", float("nan")) * 1e6,
                          "P_schreier_best_uW": a.get("schreier", {}).get("P_best_W", float("nan")) * 1e6,
                          "P_lowrate_floor_uW": a.get("lowrate_floor", {}).get("P_W", float("nan")) * 1e6,
                          "lowrate_floor_design": a.get("lowrate_floor", {}).get("design")}
        spec[mod] = row
        md += [f"\n## {mod.upper()} ({n_ch} channel{'s' if n_ch > 1 else ''})\n",
               f"| spec | one at a time ({basis}) | all at once ({comb_basis or 'combined point not run yet'}) |",
               "|---|---|---|"]
        def line(lbl, key, unit, fmt="{:g}"):
            v = s[key]
            c = cm.get(key) if cm else None
            cs = "-" if not cm else ("not included" if c is None else ("off (backed off)" if c[0] == "off"
                                                                       else f"{fmt.format(c[1])} {unit}"))
            if v["kind"] == "pending":
                md.append(f"| {lbl} | pending (full-data step-down not finished) | {cs} |")
            elif v["value"] is None:
                md.append(f"| {lbl} | not swept | {cs} |")
            else:
                md.append(f"| {lbl} | {v['kind']} {fmt.format(v['value'])} {unit} | {cs} |")
        line("input-referred noise, 0.5-100 Hz", "white", "uV rms")
        line("1/f corner at 1 uV rms white", "pink", "Hz")
        line("LSB (input-referred)", "lsb", "uV")
        line("input range (clip level)", "clip", "uV")
        line("gain error, positive", "gain+", "(relative)")
        line("gain error, negative", "gain-", "(relative)")
        line("DC offset", "offset", "x 8192 uV")
        line("drift (tau 64 s)", "drift", "uV rms")
        line("50 Hz interference", "mains50", "uV peak")
        line("250 Hz interference (aliases to 6 Hz)", "mains250", "uV peak")
        line("high-pass corner", "hp", "Hz")
        line("low-pass corner", "lp", "Hz")
        if "adc" in row:
            a = row["adc"]
            md.append(f"| ADC resolution, ceil(log2(2 C / q)) | | {a['bits']} bits (ideal SNDR {a['sndr_dB']:.1f} dB); "
                      f"from {row['power_basis']} |")
            md.append(f"| ADC power per channel (Murmann survey, adc_power.py) | | FOM scaling "
                      f"{a['P_schreier_best_uW']:.2g}-{a['P_walden_best_uW']:.2g} uW; lowest real low-rate design "
                      f"{a['P_lowrate_floor_uW']:.2g} uW |")
        if "amp_power_uW_per_channel" in row:
            p = ", ".join(f"{k}: {v:.3g} uW" for k, v in row["amp_power_uW_per_channel"].items())
            md.append(f"| amplifier power per channel (noise-set lower bound; NEF definition, VDD 1.8 V, 300 K) | | "
                      f"{p}; from {row['power_basis']} |")
    out = {"constants": {"T_K": T_K, "U_T_V": U_T, "BW_Hz": BW_HZ, "VDD_V": VDD, "fsnyq_Hz": FSNYQ, "NEF": NEFS},
           "source": str(src), "basis": basis, "combined_basis": comb_basis, "modalities": spec}
    dst = P1 if src.parent == P1 else src.parent
    (dst / "spec.json").write_text(json.dumps(out, indent=1, default=str) + "\n")
    (dst / "spec_table.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
