#!/usr/bin/env python3
"""Cross-check of two independent subset sweeps: the LSB limit and the white-noise limit (MS_SPEC.md step 6).

Textbook model: rounding to a step q adds an error of power q^2/12, spread evenly over 0..fs/2 when the error is
white. The part inside the band the front end analyses is q/sqrt(12) * sqrt(B / (fs/2)) rms. If the detector
reacts to in-band noise power only, the LSB limit expressed this way should sit between the white-noise limit and
the first failing white-noise level, and the first failing LSB likewise.

The white-error model needs a signal that moves over many steps between samples. Near and above the signal level
(EEG median 13 uV, quietest second 7 uV, signal_levels.json) the error becomes signal-dependent (a coarse quantiser
also removes small features), so a disagreement at large q is expected and is reported, not hidden.

Bands: biopotentials 0.5-100 Hz at fs 256 Hz (grids.BAND_HZ); motion 0-12.5 Hz at fs 25 Hz (the whole band).
Usage: python ms/py/consistency.py [tolerance.json] -> ms/results/phase1/consistency.json, consistency.md
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
P1 = REPO / "ms/results/phase1"
BAND = {"eeg": (99.5, 128.0), "ecg": (99.5, 128.0), "emg": (99.5, 128.0), "mov": (12.5, 12.5)}


def inband_qnoise(q: float, band_hz: float, nyq_hz: float) -> float:
    return q / math.sqrt(12.0) * math.sqrt(band_hz / nyq_hz)


def check(fams: dict, mod: str) -> dict | None:
    lsb, white = fams.get(f"{mod}/lsb"), fams.get(f"{mod}/white")
    if not lsb or not white:
        return None
    b, nyq = BAND[mod]
    qn = lambda q: None if q is None else inband_qnoise(q, b, nyq)
    w_lo = white["limit"] if white["status"] != "none tolerated" else None   # largest tolerated white rms
    w_hi = white["first_failing"]                                             # smallest failing white rms
    r = {"lsb_status": lsb["status"], "lsb_limit": lsb["limit"], "lsb_first_failing": lsb["first_failing"],
         "qnoise_at_limit": qn(lsb["limit"]), "qnoise_at_first_failing": qn(lsb["first_failing"]),
         "white_status": white["status"], "white_limit": w_lo, "white_first_failing": w_hi,
         "band_hz": b, "nyquist_hz": nyq}
    # agreement: the q-noise at the LSB limit is not above the first failing white level, and the q-noise at the
    # first failing LSB is not below the white limit (the two failure intervals overlap)
    ok_lo = r["qnoise_at_limit"] is None or w_hi is None or r["qnoise_at_limit"] < w_hi
    ok_hi = r["qnoise_at_first_failing"] is None or w_lo is None or r["qnoise_at_first_failing"] > w_lo
    r["agree"] = bool(ok_lo and ok_hi)
    return r


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else P1 / "tolerance.json"
    tol = json.loads(src.read_text())
    out, md = {}, ["# LSB limit vs white-noise limit (subset sweeps)\n",
                   f"Generated by `python ms/py/consistency.py` from `{src.name}`. In-band quantisation noise = "
                   "q/sqrt(12) * sqrt(B/(fs/2)) (white-error model; see the script header for where it fails).\n",
                   "| modality | LSB limit -> in-band q-noise | first failing LSB -> q-noise | white-noise limit | "
                   "first failing white | intervals agree |", "|---|---|---|---|---|---|"]
    f = lambda v, u="": "-" if v is None else f"{v:.3g}{u}"
    for mod, g in tol["grids"].items():
        r = check(g["families"], mod)
        if r is None:
            continue
        out[mod] = r
        u = " LSB" if mod == "mov" else " uV"
        md.append(f"| {mod} | {f(r['lsb_limit'], u)} -> {f(r['qnoise_at_limit'], u)} rms | "
                  f"{f(r['lsb_first_failing'], u)} -> {f(r['qnoise_at_first_failing'], u)} rms | "
                  f"{f(r['white_limit'], u)} rms | {f(r['white_first_failing'], u)} rms | {'yes' if r['agree'] else 'NO'} |")
    dst = P1 if src.parent == P1 else src.parent
    (dst / "consistency.json").write_text(json.dumps(out, indent=1) + "\n")
    (dst / "consistency.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
