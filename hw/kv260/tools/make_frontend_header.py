#!/usr/bin/env python3
"""Generate board/frontend/seizelut_fe_params.h from the golden model's single source of truth
(src/features/spec.py): constants, the SPT biquad coefficients, the 117-feature order and the context sources.
Run in the project repository: python hw/kv260/tools/make_frontend_header.py"""
from __future__ import annotations

import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(KIT.parents[1] / "src"))
from seizelut.features import spec as S  # noqa: E402


def main() -> int:
    L = ["/* Generated by hw/kv260/tools/make_frontend_header.py from src/features/spec.py -- do not edit. */",
         "#pragma once", "#include <stdint.h>"]
    for name in ("FS_BIO", "FS_MOV", "BLOCK_BIO", "BLOCK_MOV", "FILTER_STATE_BITS", "LOG_FRAC", "EMA_GUARD_BITS",
                 "CONTEXT_SHIFT", "MOV_OFFSET_SHIFT", "ART_LOW_SUM", "ART_HIGH_SUM", "ECG_INTEG", "ECG_REFRACTORY",
                 "ECG_SPK_SHIFT", "ECG_THR_SHIFT", "ECG_WARMUP", "ECG_HR_WINDOW_S", "ECG_RR_MIN", "ECG_RR_MAX",
                 "ECG_MIN_RR", "ECG_MAX_GAP_S", "MOV_ACT_THR"):
        L.append(f"#define {name} {int(getattr(S, name))}")
    L.append("typedef struct { int64_t b0, b1, b2, a1, a2; int frac; } fe_coef;")
    for name, bq in S.FILTERS.items():
        L.append(f"static const fe_coef C_{name} = {{{bq.b[0]}, {bq.b[1]}, {bq.b[2]}, {bq.a[0]}, {bq.a[1]}, "
                 f"{bq.frac_bits}}};")
    L.append(f"#define N_FEATURES {len(S.FEATURES)}")
    for i, f in enumerate(S.FEATURES):
        L.append(f"#define F_{f} {i}")
    L.append(f"#define N_CTX {len(S.CONTEXT_SOURCES)}")
    L.append("static const int CTX_SRC[N_CTX] = {" + ", ".join(f"F_{k}" for k in S.CONTEXT_SOURCES) + "};")
    L.append("static const int CTX_DST[N_CTX] = {" + ", ".join(f"F_{k}_ctx" for k in S.CONTEXT_SOURCES) + "};")
    L.append("static const int CTX_MOD[N_CTX] = {" + ", ".join(str(S.modality_index(k)) for k in S.CONTEXT_SOURCES)
             + "};   /* -1 EEG, 0 ECG, 1 EMG, 2 ACC, 3 GYR */")
    L.append(f"static const char *FEATURE_NAMES[N_FEATURES] = {{" + ", ".join(f'"{f}"' for f in S.FEATURES) + "};")
    out = KIT / "board" / "frontend" / "seizelut_fe_params.h"
    out.write_text("\n".join(L) + "\n")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
