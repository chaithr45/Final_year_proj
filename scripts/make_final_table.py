#!/usr/bin/env python3
"""M6 result table: every final run (results/runs/*_final_s0/final_metrics.json, 5 seeds, 29 test patients) and the
clean ChronoNet baseline (M2, 1 seed), at each model's best-F1 operating point chosen on the inner folds.

Per model: window AUROC/AUPR (mean over seeds), SzCORE event metrics (mean over patients, then mean +- std over seeds),
sensitivity at the <= 1 FA/h operating point, the dataset paper's metrics on our alarms, estimated cost, and paired
Wilcoxon tests on per-patient event-F1 (averaged over seeds) against clean ChronoNet and against LightGBM.

Usage:  python scripts/make_final_table.py
Output: results/tables/final_test.md, paper/tables/final_test.tex, results/tables/final_test.json
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
from seizelut.eval.stats import paired_wilcoxon  # noqa: E402

CHRONONET = REPO / "results/runs/20261107-204035_chrononet_clean_s1/metrics.json"
LABEL = {"n4_distill": "DWN + distillation (final)", "dwn_L50_b8_lgbm40_e15bg10": "DWN base",
         "n6_dropout": "DWN + modality dropout", "lgbm": "LightGBM", "xgb": "XGBoost", "catboost": "CatBoost",
         "rf": "Random forest", "lr": "Logistic regression", "treelut_w5": "TreeLUT (5-bit leaves)",
         "mlp_int8": "INT8 MLP", "lgn_mi40": "Logic-gate network"}
ORDER = list(LABEL)


def per_subject_f1(m, op="best_f1"):
    seeds = m["seeds"]
    subs = sorted(next(iter(seeds.values()))[op]["per_subject"])
    return {s: float(np.mean([seeds[k][op]["per_subject"][s]["f1"] for k in seeds])) for s in subs}


def load_finals():
    out = {}
    for d in sorted((REPO / "results/runs").glob("*_final_s0")):
        f = d / "final_metrics.json"
        if not f.exists() or (d / ".gitignore").exists():
            continue
        m = json.loads(f.read_text())
        name = re.match(r"^\d{8}-\d{6}_(.+)_final_s\d+$", d.name).group(1)
        out[name] = (d.name, m)
    return out


def summarise(name, run, m, ref):
    seeds = m["seeds"]
    s = m["summary_mean_std_over_seeds"]
    auroc = np.mean([v["window_auroc"] for v in seeds.values()])
    aupr = np.mean([v["window_aupr"] for v in seeds.values()])
    paper_sens = np.mean([v["best_f1"]["paper_metrics"]["sens_ovlp_mean_over_recordings"] for v in seeds.values()])
    paper_fa = np.mean([v["best_f1"]["paper_metrics"]["fa_per_hour_mean_over_recordings"] for v in seeds.values()])
    cost = next(iter(seeds.values())).get("cost") or {}
    luts = [v.get("cost", {}).get("total_luts") for v in seeds.values() if v.get("cost", {}).get("total_luts")]
    row = {"name": name, "run": run, "auroc": auroc, "aupr": aupr,
           "f1": s["best_f1"]["f1"], "sens": s["best_f1"]["sensitivity"], "prec": s["best_f1"]["precision"],
           "fp": s["best_f1"]["fp_per_24h"], "sens1": s["sens_at_1fah"]["sensitivity"],
           "fp1": s["sens_at_1fah"]["fp_per_24h"], "paper_sens": paper_sens, "paper_fa_h": paper_fa,
           "luts": float(np.median(luts)) if luts else None, "mult": cost.get("multipliers")}
    f1s = per_subject_f1(m)
    for key, other in ref.items():
        subs = sorted(set(f1s) & set(other))
        d = np.array([f1s[x] - other[x] for x in subs])
        row[f"vs_{key}"] = {"mean_diff": float(d.mean()), **paired_wilcoxon([f1s[x] for x in subs], [other[x] for x in subs])}
    return row


def main() -> int:
    finals = load_finals()
    ch = json.loads(CHRONONET.read_text())["szcore"]["0.50"]
    ref = {"chrononet": {k: v["f1"] for k, v in ch["per_subject"].items()}}
    if "lgbm" in finals:
        ref["lgbm"] = per_subject_f1(finals["lgbm"][1])
    rows = [summarise(n, *finals[n], ref) for n in ORDER if n in finals]
    rows += [summarise(n, *finals[n], ref) for n in finals if n not in ORDER]
    cm = ch["mean_over_subjects"]
    md = ["# Final evaluation on the 29 test patients (M6)\n",
          "Each model retrained on all 96 training patients with 5 seeds and scored once on sub-097..sub-125 at the "
          "best-F1 operating point chosen on the inner folds (design frozen in D39). SzCORE event metrics, mean over "
          "patients, mean +- std over seeds. p: paired Wilcoxon on per-patient event-F1 (mean over seeds). "
          "Generated by `python scripts/make_final_table.py`.\n",
          "| Model | AUROC | Event-F1 | Sens | Prec | FP/24h | Sens @<=1 FA/h (FP/24h) | Paper sens / FA/h | Est. LUTs | Mult. | vs ChronoNet: dF1, p | vs LightGBM: dF1, p |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]

    def ms(x, n=3):
        return f"{x['mean']:.{n}f} ± {x['std']:.{n}f}"

    for r in rows:
        vc, vl = r.get("vs_chrononet"), r.get("vs_lgbm")
        lgbm_cell = f"{vl['mean_diff']:+.3f}, {vl['p']:.2g}" if vl and r["name"] != "lgbm" else "-"
        md.append(f"| {LABEL.get(r['name'], r['name'])} | {r['auroc']:.3f} | {ms(r['f1'])} | {ms(r['sens'])} | "
                  f"{ms(r['prec'])} | {ms(r['fp'], 1)} | {r['sens1']['mean']:.3f} ({r['fp1']['mean']:.1f}) | "
                  f"{100 * r['paper_sens']:.1f} % / {r['paper_fa_h']:.2f} | "
                  f"{'{:,.0f}'.format(r['luts']) if r['luts'] else '-'} | {r['mult'] if r['mult'] is not None else '-'} | "
                  f"{vc['mean_diff']:+.3f}, {vc['p']:.2g} | "
                  f"{lgbm_cell} |")
    md.append(f"| ChronoNet, clean (M2, 1 seed, threshold 0.5) | - | {cm['f1']:.3f} | {cm['sensitivity']:.3f} | "
              f"{cm['precision']:.3f} | {cm['fp_per_24h']:.1f} | - | 67.1 % / 11.9 | - | CNN + GRU | - | - |")
    (REPO / "results/tables").mkdir(parents=True, exist_ok=True)
    (REPO / "results/tables/final_test.md").write_text("\n".join(md) + "\n")
    (REPO / "results/tables/final_test.json").write_text(json.dumps(rows, indent=1, default=float))
    tex = [r"\begin{table}[t]\centering\caption{Held-out test patients (29): mean $\pm$ std over 5 seeds, SzCORE event "
           r"metrics at the best-F1 operating point chosen on the training folds; $p$: paired Wilcoxon on per-patient "
           r"event-F1 against clean ChronoNet.}\label{tab:test}",
           r"\resizebox{\columnwidth}{!}{\begin{tabular}{lrrrrr}\toprule",
           r"Model & F1 & Sens & FA/24h & $p$ vs ChronoNet & Cost \\ \midrule"]
    for r in rows:
        cost = f"{r['luts']:,.0f} LUTs" if r["luts"] and not r["mult"] else (f"{r['mult']:,} mult." if r["mult"] else "-")
        tex.append(f"{LABEL.get(r['name'], r['name'])} & {r['f1']['mean']:.3f}$\\pm${r['f1']['std']:.3f} & "
                   f"{r['sens']['mean']:.3f} & {r['fp']['mean']:.1f} & {r['vs_chrononet']['p']:.1g} & {cost} \\\\")
    tex.append(f"ChronoNet (clean) & {cm['f1']:.3f} & {cm['sensitivity']:.3f} & {cm['fp_per_24h']:.1f} & -- & CNN+GRU \\\\")
    tex.append(r"\bottomrule\end{tabular}}\end{table}")
    (REPO / "paper/tables").mkdir(parents=True, exist_ok=True)
    (REPO / "paper/tables/final_test.tex").write_text("\n".join(tex) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
