#!/usr/bin/env python3
"""M3: integer-vs-float gap of the golden front end (Section 5, float twin).

For every run present in both cache/features/int and cache/features/float (training patients
only): per-feature Pearson correlation and mean |int - float| (in feature LSBs), agreement of the
artefact flags, and the window AUROC of a LightGBM model trained with leave-patients-out CV on the
same windows with integer vs float features. Writes results/m3/int_float_gap.{json,md}.

Usage: python scripts/m3_int_float_gap.py [--folds 5]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from seizelut.data.featureset import FeatureStore
from seizelut.data.split import official_train_subjects
from seizelut.features import spec as S

REPO = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--bg-ratio", type=float, default=20)
    args = ap.parse_args()
    fi, ff = FeatureStore("int"), FeatureStore("float")
    train = set(official_train_subjects())
    keys = sorted(k for k in ff.runs_of(sorted(train)) if (fi.dir / f"{k}.npz").exists())
    if not keys:
        print("no float-twin runs cached")
        return 1
    Xi, Xf, Y, G, Ai, Af = [], [], [], [], [], []
    for k in keys:
        a, b = fi.load_run(k), ff.load_run(k)
        n = min(len(a.X), len(b.X))
        Xi.append(a.X[:n].astype(np.float64)); Xf.append(b.X[:n].astype(np.float64))
        Y.append(a.y[:n]); G += [a.subject] * n
        Ai.append(a.artefact[:n]); Af.append(b.artefact[:n])
    Xi, Xf, Y, G = np.concatenate(Xi), np.concatenate(Xf), np.concatenate(Y), np.array(G)
    Ai, Af = np.concatenate(Ai), np.concatenate(Af)
    per_feat = {}
    for j, name in enumerate(S.FEATURES):
        a, b = Xi[:, j], Xf[:, j]
        r = float(np.corrcoef(a, b)[0, 1]) if a.std() > 0 and b.std() > 0 else float("nan")
        per_feat[name] = {"pearson": r, "mean_abs_diff_lsb": float(np.mean(np.abs(a - b))),
                          "p99_abs_diff_lsb": float(np.percentile(np.abs(a - b), 99))}
    art = {f"ch{c + 1}": float(np.mean(Ai[:, c] == Af[:, c])) for c in range(Ai.shape[1])}

    # leave-patients-out LightGBM on both feature versions, same windows, same folds
    import lightgbm as lgb
    from sklearn.metrics import average_precision_score, roc_auc_score
    rng = np.random.default_rng(0)
    subs = np.array(sorted(set(G)))
    rng.shuffle(subs)
    fold_of = {s: i % args.folds for i, s in enumerate(subs)}
    F = np.array([fold_of[g] for g in G])
    auc = {}
    for tag, X in (("int", Xi), ("float", Xf)):
        oof = np.full(len(Y), np.nan)
        for k in range(args.folds):
            tr, va = np.flatnonzero(F != k), np.flatnonzero(F == k)
            pos, neg = tr[Y[tr] == 1], tr[Y[tr] == 0]
            neg = rng.choice(neg, size=min(len(neg), int(args.bg_ratio * max(len(pos), 1))), replace=False)
            idx = np.concatenate([pos, neg])
            m = lgb.LGBMClassifier(n_estimators=300, learning_rate=0.05, num_leaves=31, verbose=-1, random_state=0)
            m.fit(X[idx], Y[idx])
            oof[va] = m.predict_proba(X[va])[:, 1]
        auc[tag] = {"window_auroc": float(roc_auc_score(Y, oof)), "window_aupr": float(average_precision_score(Y, oof))}
    corr = np.array([v["pearson"] for v in per_feat.values()])
    out = {"runs": len(keys), "subjects": sorted(set(G.tolist())), "windows": int(len(Y)),
           "seizure_windows": int(Y.sum()), "artefact_agreement": art,
           "pearson_min": float(np.nanmin(corr)), "pearson_median": float(np.nanmedian(corr)),
           "n_features_pearson_below_0.95": int(np.sum(corr < 0.95)),
           "lgbm_leave_patients_out": auc, "per_feature": per_feat}
    d = REPO / "results" / "m3"
    d.mkdir(parents=True, exist_ok=True)
    (d / "int_float_gap.json").write_text(json.dumps(out, indent=1) + "\n")
    worst = sorted(per_feat.items(), key=lambda kv: (kv[1]["pearson"] if kv[1]["pearson"] == kv[1]["pearson"] else -1))[:10]
    md = ["# M3 integer vs float twin of the golden front end\n",
          f"{len(keys)} runs from {len(set(G))} training patients, {len(Y):,} windows ({int(Y.sum()):,} seizure). "
          "Generated by `python scripts/m3_int_float_gap.py`.\n",
          f"* Pearson correlation int vs float over {len(S.FEATURES)} features: min {out['pearson_min']:.4f}, "
          f"median {out['pearson_median']:.4f}; {out['n_features_pearson_below_0.95']} below 0.95.",
          "* Artefact flag agreement: " + ", ".join(f"{k} {v:.4f}" for k, v in art.items()) + ".",
          f"* LightGBM, {args.folds}-fold leave-patients-out on these windows: int AUROC "
          f"{auc['int']['window_auroc']:.4f} / AUPR {auc['int']['window_aupr']:.4f}; float AUROC "
          f"{auc['float']['window_auroc']:.4f} / AUPR {auc['float']['window_aupr']:.4f}.\n",
          "Lowest-correlation features:\n", "| Feature | Pearson | mean abs diff (LSB) | p99 abs diff (LSB) |",
          "|---|---|---|---|"]
    md += [f"| {n} | {v['pearson']:.4f} | {v['mean_abs_diff_lsb']:.3f} | {v['p99_abs_diff_lsb']:.1f} |" for n, v in worst]
    (d / "int_float_gap.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
