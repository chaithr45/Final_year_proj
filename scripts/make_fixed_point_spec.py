#!/usr/bin/env python3
"""Generate spec/fixed_point.md from src/features/spec.py (the single source of truth).

Usage:  python scripts/make_fixed_point_spec.py [--maxabs cache/features/int/maxabs.json]
The optional maxabs file (written by scripts/extract_features.py) adds the largest value
observed on the data next to each declared width.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from seizelut.features import spec as S
from seizelut.features.fixedpoint import biquad_response_db, spt_terms

REPO = Path(__file__).resolve().parents[1]


def describe(name: str) -> str:
    base = name[:-4] if name.endswith("_ctx") else name
    parts = {
        "mav": "log2 of the 2 s sum of |1-25 Hz EEG|", "ll": "log2 of the 2 s line length of the 1-25 Hz EEG",
        "mob": "Hjorth-mobility proxy: log2(line length) - log2(sum|x|)", "zc": "zero crossings in 2 s",
        "ext": "local extrema (slope sign changes) in 2 s", "delta": "log2 sum |1-4 Hz|", "theta": "log2 sum |4-8 Hz|",
        "alpha": "log2 sum |8-13 Hz|", "beta": "log2 sum |13-25 Hz|", "hf": "log2 sum |25-60 Hz| (muscle)",
    }
    if base.startswith("eeg_ch"):
        ch, k = base.split("_")[1], "_".join(base.split("_")[2:])
        d = f"channel {ch[-1]}: {parts[k]}"
    elif base.startswith("eeg_") and base.rsplit("_", 1)[-1] in ("mean", "max", "absdiff"):
        k, agg = base[4:].rsplit("_", 1)
        d = {"mean": "(c1 + c2) >> 1 of ", "max": "max(c1, c2) of ", "absdiff": "|c1 - c2| of "}[agg] + parts[k]
    else:
        d = {"eeg_sign_agree": "samples in 2 s where both 1-25 Hz channels have the same sign",
             "eeg_art_ch1": "artefact flag ch1: 2 s sum|0.5-60 Hz, notch| outside "
                            f"[{S.ART_LOW_SUM}, {S.ART_HIGH_SUM}] (= RMS 13-150 uV for Gaussian signals)",
             "eeg_art_ch2": "artefact flag ch2 (same rule)",
             "ecg_log_rr": "log2(sum RR) - log2(#RR) over the last 10 s (log mean RR in samples)",
             "ecg_log_masrd": "log2(sum |dRR|) - log2(#dRR) over the last 10 s",
             "ecg_quality_bad": "<3 RR in 10 s, or an RR outside 0.3-2 s, or no beat in 3 s",
             "emg_mav": "log2 sum |EMG > 20 Hz|", "emg_ll": "log2 line length of EMG > 20 Hz",
             "emg_zc": "zero crossings of EMG > 20 Hz", "emg_hl_ratio": "log2 sum|> 60 Hz| - log2 sum|20-60 Hz|",
             }.get(base)
        if d is None and base.startswith("mov_"):
            s, k = base.split("_")[1], base.split("_")[2]
            d = f"chest {s.upper()} " + {"mag": "log2 sum of L1 magnitude (offset removed)",
                                         "jerk": "log2 sum over axes of |x[n]-x[n-1]|",
                                         "act": f"samples with L1 > {S.MOV_ACT_THR} counts",
                                         "band": "log2 sum over axes of |1-5 Hz|"}[k]
        if d is None and base.startswith("present_"):
            d = f"{base[8:].upper()} present bit"
    if name.endswith("_ctx"):
        d = f"context: value - EMA_64s(value) of [{d}]"
    return d


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--maxabs", default=str(REPO / "cache/features/int/maxabs.json"))
    ap.add_argument("--out", default=str(REPO / "spec/fixed_point.md"))
    args = ap.parse_args()
    maxabs = json.loads(Path(args.maxabs).read_text()) if Path(args.maxabs).exists() else {}
    L = ["# Fixed-point specification (golden model)\n",
         "Generated by `python scripts/make_fixed_point_spec.py` from `src/features/spec.py`. "
         "The golden model (`src/features/golden.py`) follows this table; `scripts/extract_features.py` "
         "fails if any feature exceeds its declared width, and `tests/test_features.py` checks it on the fixture.\n",
         "## 1. Signals and arithmetic\n",
         "| Signal | Width (signed bits) | Scale | Rounding | Saturation |", "|---|---|---|---|---|",
         f"| EEG/ECG/EMG input | {S.INPUT_BITS} | {S.LSB_BIO} uV/LSB at {S.FS_BIO} Hz | round to nearest (replay software) | clip to int16 |",
         f"| Motion input (chest ACC, GYR) | {S.INPUT_BITS} | 2^-12 unit/LSB at {S.FS_MOV} Hz | round to nearest (replay software) | clip to int16 |",
         f"| Biquad coefficients | <= 18 | 2^-{S.FILTER_FRAC_BITS} | SPT, <= 5 terms | - |",
         f"| Biquad accumulator | 40 | 2^-{S.FILTER_FRAC_BITS} x input LSB | floor, 2nd-order error feedback of the {S.FILTER_FRAC_BITS} discarded bits | - |",
         f"| Biquad output (filter state) | {S.FILTER_STATE_BITS} | input LSB | - | clip to int{S.FILTER_STATE_BITS} |",
         "| 1-s block sums of |x| | 29 | input LSB | exact | none needed (256 x 2^20) |",
         "| 2-s window sums | 30 | input LSB | exact (sum of two block registers) | none |",
         f"| log2 values | 9 | 2^-{S.LOG_FRAC} | leading-one position + {S.LOG_FRAC} truncated mantissa bits; log2(0)=log2(1)=0 | - |",
         "| Counts (zero crossings, extrema, sign agreement, activity) | 11 | count per 2 s window | exact | - |",
         f"| Context EMA register | 16 | 2^-{S.EMA_GUARD_BITS} x feature LSB | floor (arithmetic shift) | - |",
         f"| Motion offset EMA register | 24 | 2^-{S.EMA_GUARD_BITS + 2} x input LSB | floor | - |",
         "| ECG moving integration | 23 | input LSB | exact (32-sample running sum) | - |",
         "| Thermometer inputs | = feature width | feature LSB | comparator `x > threshold` | - |",
         "| LUT-network score | ceil(log2(neurons per class))+1 | popcount difference | exact | - |",
         "",
         "Every feature is stored as int16 in `cache/features/int/`.\n",
         "## 2. Filters (2nd-order sections, Butterworth unless noted)\n",
         "| Name | b0, b1, b2 | a1, a2 | SPT terms | Max deviation from float design (dB, where the design is above -40 dB) |",
         "|---|---|---|---|---|"]
    for bq in S.FILTERS.values():
        fs = S.FS_MOV if bq.name.startswith("mov") else S.FS_BIO
        fr = np.linspace(0.25, fs / 2 - 0.25, 400)
        if bq.name.endswith("notch50"):
            fr = fr[np.abs(fr - 50) > 2]
        ref = biquad_response_db(bq, fr, fs, False)
        keep = ref > -40          # passband and transition band; stopband reported as a floor
        dev = np.max(np.abs(biquad_response_db(bq, fr, fs)[keep] - ref[keep]))
        L.append(f"| {bq.name} | {bq.b} | {bq.a} | {sum(spt_terms(c) for c in (*bq.b, *bq.a))} | {dev:.3f} |")
    L += ["", "Per-channel datapath: " + "; ".join(f"{m.upper()}: {len(v)} biquads" for m, v in S.FILTER_USE.items()) + ".\n",
          "## 3. Features (window t = seconds [t, t+2), available at the end of second t+1)\n",
          "| # | Name | Definition | Declared width | Max |value| seen |", "|---|---|---|---|---|"]
    for i, n in enumerate(S.FEATURES):
        L.append(f"| {i} | `{n}` | {describe(n)} | {S.FEATURE_BITS[n]} | {int(maxabs[n]) if n in maxabs else '-'} |")
    L += ["", "## 4. Constants\n", "| Constant | Value |", "|---|---|"]
    for k in ["ART_LOW_SUM", "ART_HIGH_SUM", "ECG_INTEG", "ECG_REFRACTORY", "ECG_SPK_SHIFT", "ECG_THR_SHIFT",
              "ECG_WARMUP", "ECG_HR_WINDOW_S", "ECG_RR_MIN", "ECG_RR_MAX", "MOV_ACT_THR", "MOV_OFFSET_SHIFT", "CONTEXT_SHIFT"]:
        L.append(f"| {k} | {getattr(S, k)} |")
    L += ["", "Multipliers in the feature front end: **0** (all constant products are shift-adds; "
          "no data x data products: RMS is replaced by mean absolute value, power by sum of |x|).\n"]
    Path(args.out).write_text("\n".join(L) + "\n")
    print(args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
